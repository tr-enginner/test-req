/**
 * Generate a diagnostic test script that probes the simulation environment
 * for common configuration problems (register accessibility, UART response, etc.).
 *
 * The script uses built-in diagnostic commands (diag_check_register,
 * diag_write_read_verify, diag_send_and_wait) added to the test driver.
 */
export function generateDiagnosticScript(
  devices: Array<{
    device_name: string
    device_type: string
    registers: Array<{ name: string; address: string; role?: string }>
    ports: Array<{ name: string; type: string; direction?: string }>
    protocol_params?: Record<string, string>
  }>,
): string {
  const lines: string[] = []

  lines.push(`;; ====== Auto-generated Diagnostic Script ======`)
  lines.push(`;; Generated by matrix-embedded-agent`)
  lines.push(`;; Purpose: Verify simulation environment configuration`)
  lines.push(`;;`)

  let time = 0.1

  // Phase 1: Register accessibility check
  lines.push(`;; Phase 1: Register accessibility check`)
  for (const dev of devices) {
    if (dev.registers.length === 0) continue
    const firstReg = dev.registers[0]
    lines.push(`;; Device: ${dev.device_name} (${dev.device_type})`)
    lines.push(`#${time.toFixed(1)},diag_check_register,addr=${firstReg.address}|type=2|count=${Math.min(dev.registers.length, 8)}`)
    time += 0.1

    // Write-read verify on first register
    lines.push(`#${time.toFixed(1)},diag_write_read_verify,addr=${firstReg.address}|type=2|write_val=0xAA`)
    time += 0.1
  }

  // Phase 2: UART/RS422 loopback test
  lines.push(`;;`)
  lines.push(`;; Phase 2: UART communication test`)
  for (const dev of devices) {
    if (dev.device_type !== "uart" && dev.device_type !== "rs422") continue
    const vport = dev.ports.find((p) => p.type === "vport")
    if (!vport) continue

    // Build a sample frame from protocol params
    const header = dev.protocol_params?.frame_header || ""
    const tail = dev.protocol_params?.frame_tail || ""
    let sampleData = header + "0102030405" + tail
    if (!header) sampleData = "0102030405"

    lines.push(`;; UART test: ${dev.device_name}`)
    lines.push(`#${time.toFixed(1)},diag_send_and_wait,port=0|data=${sampleData}|wait_ms=1000`)
    time += 1.5
  }

  // Phase 3: Wait and stop
  lines.push(`;;`)
  lines.push(`;; Phase 3: Collect diagnostics and stop`)
  time = Math.max(time, 3.0)
  lines.push(`#${time.toFixed(1)},stop_simulation,reason=diagnostic_complete`)

  return lines.join("\n") + "\n"
}
