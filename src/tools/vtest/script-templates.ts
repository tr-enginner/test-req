  lines.push(``)
  lines.push(`- **默认路径**: 与结果 JSON 文件同目录，扩展名改为 \`.csv\``)
  lines.push(`- **可配置**: 通过 \`[DeviceProperty]\` 设置 \`RecordFile=<路径>\``)
  lines.push(``)
  lines.push(`**CSV 格式**:`)
  lines.push(``)
  lines.push("```csv")
  lines.push(`sim_time,event,details`)
  lines.push(`0.000000,INIT, driver=${driverName}, commands=5`)
  lines.push(`0.000000,RESET, time=0.000000`)
  lines.push(`0.100000,CMD_EXEC, time=0.100000, index=0, cmd=set_adc_input, params=ch0=2048`)
  lines.push(`0.200000,VPORT_RX, time=0.200000, port=uart_rx, size=4, data=A1 B2 C3 D4`)
  lines.push(`10.000000,ALL_DONE, total=5, time=10.000000`)
  lines.push("```")
  lines.push(``)
  lines.push(`**记录的事件类型**:`)
