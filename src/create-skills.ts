import { join } from "path"
import { runtimeAssetRoot } from "./shared/runtime-paths"

/**
 * Resolve the path to the bundled skills directory.
 *
 * Skills are shipped as SKILL.md files under `skills/<name>/SKILL.md`
 * at the plugin package root. Since the built entry point lives in `dist/`,
 * we go one level up to reach the package root.
 */
export function resolveSkillsDir(): string {
  return join(runtimeAssetRoot(import.meta.url), "skills")
}

