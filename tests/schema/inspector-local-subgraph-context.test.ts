import { describe, expect, test } from "bun:test"
import {
  InspectorLocalSubgraphContext,
  InspectorLocalSubgraphManifest,
} from "../../src/schema/context-pack"

describe("InspectorLocalSubgraphContext", () => {
  test("accepts the local_subgraph manifest shape generated by code-slice", () => {
    const parsed = InspectorLocalSubgraphManifest.safeParse({
      project_path: "D:/repo",
      generated_at: "2026-05-11T05:52:18Z",
      context_count: 1,
      contexts: [
        {
          context_id: "ctx-0001",
          entry_name: "boot",
          slicing_strategy: "local_subgraph",
          block_kind: "local_subgraph",
          file: "contexts/ctx-0001.json",
        },
      ],
    })

    expect(parsed.success).toBe(true)
  })

  test("accepts the local_subgraph context shape generated by code-slice", () => {
    const parsed = InspectorLocalSubgraphContext.safeParse({
      context_id: "ctx-0001",
      block: {
        block_id: "e96f9a6f113f",
        block_kind: "local_subgraph",
        slicing_strategy: "local_subgraph",
        root_function_name: "boot",
        function_ids: [2, 1, 4],
      },
      outline: {
        globals: ["g_ctx"],
        types: ["device_ctx_t"],
        macros: ["BOOT_INCREMENT", "RECORD_MACRO_STATE"],
        function_region: ["boot", "compute_limit"],
      },
      locations: {
        functions: [
          { name: "boot", path: "src/entry.c", start_line: 19, end_line: 38 },
        ],
        globals: [
          { name: "g_ctx", path: "src/state.c", line: 6 },
        ],
        types: [
          { name: "device_ctx_t", path: "include/model.h", start_line: 12, end_line: 17 },
        ],
        macros: [
          { name: "BOOT_INCREMENT", path: "include/model.h", start_line: 20, end_line: 20, kind: "object" },
          { name: "RECORD_MACRO_STATE", path: "include/model.h", start_line: 18, end_line: 19, kind: "function" },
        ],
        attached_comments: [
          { func_name: "boot", path: "src/entry.c", start_line: 18, end_line: 18 },
        ],
      },
      prompt_ready: {
        text: "[Context]\nid: ctx-0001\nslicing_strategy: local_subgraph",
      },
    })

    expect(parsed.success).toBe(true)
  })

  test("defaults macro fields for pre-macro local_subgraph contexts", () => {
    const parsed = InspectorLocalSubgraphContext.parse({
      context_id: "ctx-legacy",
      block: {
        block_id: "legacy",
        block_kind: "local_subgraph",
        slicing_strategy: "local_subgraph",
        root_function_name: "boot",
        function_ids: [1],
      },
      outline: {
        globals: [],
        types: [],
        function_region: ["boot"],
      },
      locations: {
        functions: [{ name: "boot", path: "src/entry.c", start_line: 1, end_line: 2 }],
        globals: [],
        types: [],
      },
      prompt_ready: {
        text: "[Context]\nid: ctx-legacy\nslicing_strategy: local_subgraph",
      },
    })

    expect(parsed.outline.macros).toEqual([])
    expect(parsed.locations.macros).toEqual([])
    expect(parsed.locations.attached_comments).toEqual([])
  })

  test("rejects path contexts", () => {
    const parsed = InspectorLocalSubgraphContext.safeParse({
      context_id: "ctx-0001",
      block: {
        block_id: "abc",
        block_kind: "path",
        slicing_strategy: "path",
        root_function_name: "boot",
        function_ids: [1],
      },
      outline: {
        globals: [],
        types: [],
      },
      locations: {
        functions: [],
        globals: [],
        types: [],
      },
      prompt_ready: {
        text: "[Context]\nid: ctx-0001",
      },
    })

    expect(parsed.success).toBe(false)
  })

  test("rejects legacy function_chain contexts", () => {
    const parsed = InspectorLocalSubgraphContext.safeParse({
      context_id: "ctx-0001",
      block: {
        block_id: "abc",
        block_kind: "local_subgraph",
        slicing_strategy: "local_subgraph",
        root_function_name: "boot",
        function_ids: [1],
      },
      outline: {
        globals: [],
        types: [],
        function_chain: ["boot", "helper"],
      },
      locations: {
        functions: [
          { name: "boot", path: "src/entry.c", start_line: 1, end_line: 10 },
        ],
        globals: [],
        types: [],
      },
      prompt_ready: {
        text: "[Context]\nid: ctx-0001\nslicing_strategy: local_subgraph",
      },
    })

    expect(parsed.success).toBe(false)
  })
})
