#ifndef HW_CONFIG_H
#define HW_CONFIG_H

/*===========================================================================
 * 卫星电源控制器 - 硬件配置与寄存器定义
 * MCU: 8051 兼容 (12 MHz)
 *===========================================================================*/

/*---------------------------------------------------------------------------
 * 8051 特殊功能寄存器 (SFR) 定义
 *---------------------------------------------------------------------------*/
sfr P0      = 0x80;     /* 端口 0: 负载开关驱动输出 */
sfr P1      = 0x90;     /* 端口 1: ADC 模拟输入 */
sfr P2      = 0xA0;     /* 端口 2: 离散遥测输出/充电控制 */
sfr P3      = 0xB0;     /* 端口 3: UART/外部中断 */

sfr TMOD    = 0x89;     /* 定时器模式寄存器 */
sfr TH0     = 0x8C;     /* 定时器 0 高字节 */
sfr TL0     = 0x8A;     /* 定时器 0 低字节 */
sfr TCON    = 0x88;     /* 定时器控制寄存器 */

sfr SCON    = 0x98;     /* 串口控制寄存器 */
sfr SBUF    = 0x99;     /* 串口数据缓冲 */

sfr IE      = 0xA8;     /* 中断使能寄存器 */
sfr IP      = 0xB8;     /* 中断优先级寄存器 */
sfr PSW     = 0xD0;     /* 程序状态字 */
sfr ACC     = 0xE0;     /* 累加器 */

sfr PCON    = 0x87;     /* 电源控制寄存器 */

/* ADC 控制寄存器 (扩展 SFR) */
sfr ADC_CTRL = 0xC0;    /* ADC 控制: [7]=启动 [6]=完成 [2:0]=通道选择 */
sfr ADC_DATL = 0xC1;    /* ADC 数据低字节 */
sfr ADC_DATH = 0xC2;    /* ADC 数据高字节 (高 4 位有效) */

/* DAC 控制寄存器 (扩展 SFR) */
sfr DAC_DATA = 0xC3;    /* DAC 输出数据 (8-bit) */
sfr DAC_CTRL = 0xC4;    /* DAC 控制: [7]=使能 [0]=更新 */

/* 看门狗控制寄存器 (扩展 SFR) */
sfr WDT_CTRL = 0xC5;    /* 看门狗控制: [7]=使能 [0]=喂狗 */

/*---------------------------------------------------------------------------
 * 位寻址定义 (sbit)
 *---------------------------------------------------------------------------*/
/* 端口 0: 负载开关 (1=接通, 0=断开) */
sbit LOAD_SW0 = P0^0;   /* 星务计算机 (关键负载) */
sbit LOAD_SW1 = P0^1;   /* 测控应答机 (关键负载) */
sbit LOAD_SW2 = P0^2;   /* 载荷 1 (非关键) */
sbit LOAD_SW3 = P0^3;   /* 载荷 2 (非关键) */
sbit LOAD_SW4 = P0^4;   /* 载荷 3 (非关键) */
sbit LOAD_SW5 = P0^5;   /* 载荷 4 (非关键) */
sbit LOAD_SW6 = P0^6;   /* 载荷 5 (非关键) */
sbit LOAD_SW7 = P0^7;   /* 载荷 6 (非关键) */

/* 端口 2: 控制输出 */
sbit CHG_EN   = P2^0;   /* 充电通路使能 (1=充电, 0=停充) */
sbit SA_SHORT = P2^1;   /* 太阳能阵列短路保护 (1=短路) */
sbit LED_RUN  = P2^6;   /* 运行指示灯 */
sbit LED_ERR  = P2^7;   /* 故障指示灯 */

/* 端口 3: 标准 8051 功能 */
sbit TXD      = P3^1;   /* UART 发送 */
sbit RXD      = P3^0;   /* UART 接收 */

/* 定时器控制位 */
sbit TR0      = TCON^4; /* 定时器 0 运行控制 */
sbit TF0      = TCON^5; /* 定时器 0 溢出标志 */

/* 串口控制位 */
sbit TI       = SCON^1; /* 发送完成中断标志 */
sbit RI       = SCON^0; /* 接收完成中断标志 */

/* 中断使能位 */
sbit EA       = IE^7;   /* 总中断使能 */
sbit ET0      = IE^1;   /* 定时器 0 中断使能 */
sbit ES       = IE^4;   /* 串口中断使能 */

/*---------------------------------------------------------------------------
 * ADC 通道定义
 *---------------------------------------------------------------------------*/
#define ADC_CH_V_SA      0    /* 太阳能阵列电压 */
#define ADC_CH_I_SA      1    /* 太阳能阵列电流 */
#define ADC_CH_V_BAT     2    /* 蓄电池电压 */
#define ADC_CH_V_BUS     3    /* 母线电压 */
#define ADC_CH_TEMP_BAT  4    /* 蓄电池温度 */
#define ADC_CH_TEMP_PCU  5    /* PCU 板温 */
#define ADC_CH_I_LOAD    6    /* 总负载电流 */
#define ADC_CH_SPARE     7    /* 备用 */

#define ADC_NUM_CHANNELS 8
#define ADC_START_BIT    0x80 /* ADC_CTRL bit 7: 启动转换 */
#define ADC_DONE_BIT     0x40 /* ADC_CTRL bit 6: 转换完成 */

/*---------------------------------------------------------------------------
 * 系统时钟与定时器配置
 *---------------------------------------------------------------------------*/
#define FOSC             12000000UL  /* 晶振频率 12 MHz */
#define TIMER0_RELOAD_H  0xD8       /* 10 ms 定时器重载值高字节 */
#define TIMER0_RELOAD_L  0xF0       /* 10 ms 定时器重载值低字节 */
#define UART_BAUD_RELOAD 0xFD       /* 9600 bps @ 12 MHz (SMOD=1) */

/*---------------------------------------------------------------------------
 * 遥测帧定义
 *---------------------------------------------------------------------------*/
#define TLM_FRAME_SYNC_H 0xEB       /* 帧同步字高字节 */
#define TLM_FRAME_SYNC_L 0x90       /* 帧同步字低字节 */
#define TLM_FRAME_LEN    16         /* 数据区长度 (字节) */

/* 遥控指令码 */
#define CMD_LOAD_SWITCH  0x01       /* 负载开关控制 */
#define CMD_MPPT_MODE    0x02       /* MPPT 模式切换 */
#define CMD_TLM_REQUEST  0x03       /* 遥测请求 */
#define CMD_RESET        0xFF       /* 复位 */

#endif /* HW_CONFIG_H */
